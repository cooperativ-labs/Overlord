/**
 * The one Overlord MCP tool catalog: names, titles, descriptions, input/output
 * schemas, and safety annotations. Both MCP surfaces project it — the hosted
 * server (`mcp/tool-catalog.ts`, which adds widget `_meta`) and the local
 * connector shim (`connectors/core/scripts/overlord-mcp.mjs`, whose `tools`
 * array is generated from this module by `scripts/generate-mcp-tool-catalog.mts`).
 * Edit tool schemas here, never in either surface.
 */
export type McpToolDefinition = {
  name: string;
  title: string;
  description: string;
  inputSchema: Record<string, unknown>;
  outputSchema: Record<string, unknown>;
  annotations: Record<string, unknown>;
};

export type McpToolCatalogOptions = {
  /** Agent identifier `overlord_attach_session` falls back to when `agent` is omitted. */
  defaultAgent: string;
};

function objectSchema(
  properties: Record<string, unknown>,
  required: string[] = []
): Record<string, unknown> {
  return {
    type: 'object',
    properties,
    required,
    additionalProperties: false
  };
}

const stringProperty = (description: string): Record<string, unknown> => ({
  type: 'string',
  description
});

function missionSummaryProperty({
  requireBase
}: {
  requireBase: boolean;
}): Record<string, unknown> {
  return {
    ...objectSchema({
      baseContentRevision: {
        type: 'integer',
        minimum: 0,
        description: requireBase
          ? 'missionSummary.contentRevision from attach. Required with headline and summary. If it is stale, the delivery is still accepted and your headline and summary are withheld.'
          : 'Not needed: record-work creates a new mission with no summary to conflict with.'
      },
      ...(requireBase
        ? {
            baseEvidenceRevision: {
              type: 'integer',
              minimum: 0,
              description:
                'missionSummary.evidenceRevision from attach. Without it, or if other accepted work changed the mission since, the delivery is still accepted and your headline and summary are withheld.'
            }
          }
        : {}),
      headline: stringProperty('One sentence, at most 140 characters. Send together with summary.'),
      summary: stringProperty(
        'Markdown, at most 1,200 characters, rewritten to be true now: what the mission provides and why it matters, current limits, then what a person must do. Say whether claims are implemented, tested or deployed. Do not restate open actions or suggestions.'
      ),
      closeItems: {
        type: 'array',
        maxItems: 50,
        description:
          'Open items of this mission (ids from the attach baseline openItems) that you checked are addressed (done) or no longer apply (dismissed). Unknown, foreign or already-closed ids are skipped with a warning.',
        items: objectSchema(
          {
            id: stringProperty('Item id from missionSummary.openItems.'),
            status: { type: 'string', enum: ['done', 'dismissed'] },
            reason: stringProperty('Required. Why, at most 280 characters. Shown to people.')
          },
          ['id', 'status', 'reason']
        )
      }
    }),
    description: requireBase
      ? 'Optional agent-written mission summary for people: a replacement headline and summary based on the attach baseline, and open items to close. Nothing else writes it. Stale or absent prose never rejects the delivery: missionSummary.publication and instruction then say how to publish once with overlord_publish_delivery_summary.'
      : 'Optional agent-written mission summary for the new mission: headline and summary. Without it, the result says how to publish once later with overlord_publish_delivery_summary.'
  };
}

const booleanProperty = (description: string): Record<string, unknown> => ({
  type: 'boolean',
  description
});

const protocolOutputSchema = (description: string): Record<string, unknown> => ({
  type: 'object',
  description,
  additionalProperties: true
});

const declaredPathsProperty = (description: string): Record<string, unknown> => ({
  type: 'array',
  description,
  items: stringProperty(
    'Canonical repository-relative path. Deleted and renamed paths (both endpoints) are valid.'
  )
});

/** Caller-retained finalization operation id (ADR 0075); never generated by a tool handler. */
function operationIdProperty(kind: 'delivery' | 'record'): Record<string, unknown> {
  return stringProperty(
    `Optional retry identity for this ${kind}: 8-128 letters, digits, ".", "_", ":" or "-". ` +
      'Choose it yourself before the first call and send the same value on every retry of this attempt (for example after a timeout or lost response); the server then returns the original result instead of ' +
      (kind === 'delivery'
        ? 'delivering again. '
        : 'recording the work twice. Use a new value only for intentionally separate work. ') +
      'The same value with a different request is refused with delivery_operation_conflict. Without it, retries are not deduplicated' +
      (kind === 'delivery' ? ' (a second delivery of the session is still refused).' : '.')
  );
}

